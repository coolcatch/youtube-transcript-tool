import { execFile } from "node:child_process";
import { mkdtemp, readFile, rm, readdir } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { promisify } from "node:util";
import { getConfig } from "../config";
import { TranscriptError, type TranscriptResult } from "../types";
import { getOEmbed } from "./oembed";
import type { Fetcher } from "./types";

const run = promisify(execFile);

/**
 * OPTIONAL fallback for videos with NO captions: download the audio with
 * yt-dlp and send it to any OpenAI-compatible /audio/transcriptions endpoint
 * (OpenAI Whisper by default; set WHISPER_API_BASE_URL + WHISPER_MODEL for
 * another compatible provider).
 *
 * Off unless TRANSCRIPT_FALLBACKS contains "whisper" AND WHISPER_API_KEY is set.
 * Needs the `yt-dlp` binary, so it works in the CLI / a self-hosted server,
 * NOT on Vercel serverless (no yt-dlp, 4.5 MB body and time limits).
 * Costs money per minute of audio. Files > 25 MB are rejected by OpenAI.
 */
export const whisperFetcher: Fetcher = {
  name: "whisper",
  async fetch(videoId, lang) {
    const { whisper } = getConfig();
    if (!whisper.apiKey) throw new TranscriptError("NOT_CONFIGURED", "WHISPER_API_KEY is not set.");
    const dir = await mkdtemp(path.join(tmpdir(), "yt-audio-"));
    try {
      try {
        await run(
          whisper.ytDlpPath,
          ["-f", "bestaudio[ext=m4a]/bestaudio", "--no-playlist", "-o", path.join(dir, "audio.%(ext)s"), `https://www.youtube.com/watch?v=${videoId}`],
          { timeout: 180_000 },
        );
      } catch (e) {
        throw new TranscriptError("NOT_CONFIGURED", `yt-dlp failed or is not installed: ${(e as Error).message}`);
      }
      const file = (await readdir(dir)).find((f) => f.startsWith("audio."));
      if (!file) throw new TranscriptError("UPSTREAM", "yt-dlp produced no audio file.");
      const buf = await readFile(path.join(dir, file));
      const form = new FormData();
      form.append("file", new Blob([buf]), file);
      form.append("model", whisper.model);
      form.append("response_format", "verbose_json");
      if (lang) form.append("language", lang.split("-")[0]);
      const res = await fetch(`${whisper.baseUrl}/audio/transcriptions`, {
        method: "POST",
        headers: { Authorization: `Bearer ${whisper.apiKey}` },
        body: form,
      });
      if (!res.ok) throw new TranscriptError("UPSTREAM", `Transcription API returned HTTP ${res.status}: ${(await res.text()).slice(0, 200)}`);
      const j = (await res.json()) as { text?: string; language?: string; segments?: { start: number; end: number; text: string }[] };
      const segments = j.segments?.length
        ? j.segments.map((s) => ({ start: s.start, duration: s.end - s.start, text: s.text.trim() }))
        : [{ start: 0, duration: 0, text: (j.text ?? "").trim() }];
      const meta = await getOEmbed(videoId);
      const language = lang ?? j.language ?? "en";
      const result: TranscriptResult = {
        videoId,
        ...meta,
        thumbnailUrl: `https://i.ytimg.com/vi/${videoId}/hqdefault.jpg`,
        language,
        languageName: `${language} (AI transcription)`,
        isAutoGenerated: true,
        tracks: [{ languageCode: language, name: `${language} (AI transcription)`, kind: "asr" }],
        segments: segments.filter((s) => s.text),
        source: "whisper",
        fetchedAt: new Date().toISOString(),
      };
      return result;
    } finally {
      await rm(dir, { recursive: true, force: true });
    }
  },
};
