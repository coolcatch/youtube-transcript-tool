import { getConfig } from "../config";
import { httpFetch } from "../http";
import { decodeEntities } from "../xml";
import { TranscriptError, type TranscriptResult } from "../types";
import { getOEmbed } from "./oembed";
import type { Fetcher } from "./types";

/**
 * OPTIONAL fallback: a paid third-party transcript API.
 * Off unless TRANSCRIPT_FALLBACKS contains "thirdparty" AND TRANSCRIPT_API_KEY is set.
 *
 * Implemented provider: Supadata (https://supadata.ai) —
 *   GET {base}/youtube/transcript?videoId=ID[&lang=xx]   header x-api-key
 *   -> { content: [{ text, offset(ms), duration(ms), lang }], lang, availableLangs }
 * NOTE: written from Supadata's public docs; NOT yet tested with a real key.
 * To add another provider, add a branch in fetch() that maps its response to TranscriptResult.
 */
export const thirdPartyFetcher: Fetcher = {
  name: "thirdparty",
  async fetch(videoId, lang) {
    const { thirdParty } = getConfig();
    if (!thirdParty.apiKey) throw new TranscriptError("NOT_CONFIGURED", "TRANSCRIPT_API_KEY is not set.");
    if (thirdParty.provider !== "supadata") {
      throw new TranscriptError("NOT_CONFIGURED", `Unknown TRANSCRIPT_API_PROVIDER "${thirdParty.provider}".`);
    }
    const qs = new URLSearchParams({ videoId });
    if (lang) qs.set("lang", lang);
    const res = await httpFetch(`${thirdParty.baseUrl}/youtube/transcript?${qs}`, {
      headers: { "x-api-key": thirdParty.apiKey },
      useProxy: false,
    });
    if (!res.ok) throw new TranscriptError("UPSTREAM", `Transcript API returned HTTP ${res.status}.`);
    const j = (await res.json()) as {
      content?: { text: string; offset: number; duration: number }[];
      lang?: string;
      availableLangs?: string[];
    };
    const segments = (j.content ?? [])
      .map((c) => ({ start: c.offset / 1000, duration: c.duration / 1000, text: decodeEntities(c.text).trim() }))
      .filter((s) => s.text);
    if (!segments.length) throw new TranscriptError("NO_CAPTIONS", "Transcript API returned no text.");
    const meta = await getOEmbed(videoId);
    const language = j.lang ?? lang ?? "en";
    const result: TranscriptResult = {
      videoId,
      ...meta,
      thumbnailUrl: `https://i.ytimg.com/vi/${videoId}/hqdefault.jpg`,
      language,
      languageName: language,
      isAutoGenerated: false,
      tracks: (j.availableLangs ?? [language]).map((l) => ({ languageCode: l, name: l, kind: "manual" as const })),
      segments,
      source: "supadata",
      fetchedAt: new Date().toISOString(),
    };
    return result;
  },
};
