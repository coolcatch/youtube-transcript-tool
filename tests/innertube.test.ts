import { afterEach, describe, expect, it, vi } from "vitest";
import { innertubeFetcher, pickTrack } from "@/lib/fetchers/innertube";
import { getTranscript } from "@/lib/transcript";
import { TranscriptError } from "@/lib/types";

const tracks = [
  { languageCode: "fr", kind: "asr", baseUrl: "https://www.youtube.com/api/timedtext?lang=fr&fmt=srv3" },
  { languageCode: "en", kind: "asr", baseUrl: "https://www.youtube.com/api/timedtext?lang=en&kind=asr&fmt=srv3" },
  { languageCode: "en-GB", baseUrl: "https://www.youtube.com/api/timedtext?lang=en-GB", name: { simpleText: "English (UK)" } },
];

describe("pickTrack", () => {
  it("prefers creator English by default", () => {
    expect(pickTrack(tracks)?.languageCode).toBe("en-GB");
  });
  it("exact, then base-language match", () => {
    expect(pickTrack(tracks, "fr")?.languageCode).toBe("fr");
    expect(pickTrack(tracks, "en")?.languageCode).toBe("en");
    expect(pickTrack(tracks, "fr-CA")?.languageCode).toBe("fr");
    expect(pickTrack(tracks, "de")).toBeUndefined();
  });
});

function mockYouTube(player: unknown, xml: string) {
  const calls: string[] = [];
  vi.stubGlobal(
    "fetch",
    vi.fn(async (url: string) => {
      calls.push(url);
      if (url.includes("/youtubei/v1/player")) return new Response(JSON.stringify(player), { status: 200 });
      if (url.includes("/api/timedtext")) return new Response(xml, { status: 200 });
      return new Response("<html></html>", { status: 200 });
    }),
  );
  return calls;
}

afterEach(() => vi.unstubAllGlobals());

describe("innertubeFetcher (mocked network)", () => {
  it("builds a result and strips fmt=", async () => {
    const calls = mockYouTube(
      {
        playabilityStatus: { status: "OK" },
        videoDetails: { title: "T", author: "A", lengthSeconds: "100" },
        captions: { playerCaptionsTracklistRenderer: { captionTracks: tracks } },
      },
      `<transcript><text start="1" dur="2">hello &amp;amp; bye</text></transcript>`,
    );
    const r = await innertubeFetcher.fetch("Eux-VGsdw8o", "en");
    expect(r.title).toBe("T");
    expect(r.author).toBe("A");
    expect(r.isAutoGenerated).toBe(true);
    expect(r.tracks).toHaveLength(3);
    expect(r.segments).toEqual([{ start: 1, duration: 2, text: "hello & bye" }]);
    expect(calls.find((c) => c.includes("timedtext"))).not.toContain("fmt=");
  });

  it("NO_CAPTIONS when the video has none", async () => {
    mockYouTube({ playabilityStatus: { status: "OK" }, videoDetails: { title: "T" } }, "");
    await expect(innertubeFetcher.fetch("Eux-VGsdw8o")).rejects.toMatchObject({ code: "NO_CAPTIONS" });
  });

  it("LANG_NOT_FOUND lists available tracks", async () => {
    mockYouTube({ playabilityStatus: { status: "OK" }, captions: { playerCaptionsTracklistRenderer: { captionTracks: tracks } } }, "");
    const err = await innertubeFetcher.fetch("Eux-VGsdw8o", "de").catch((e) => e);
    expect(err).toBeInstanceOf(TranscriptError);
    expect(err.code).toBe("LANG_NOT_FOUND");
    expect(err.tracks).toHaveLength(3);
  });

  it("BLOCKED on bot check", async () => {
    mockYouTube({ playabilityStatus: { status: "LOGIN_REQUIRED", reason: "Sign in to confirm you're not a bot" } }, "");
    await expect(innertubeFetcher.fetch("Eux-VGsdw8o")).rejects.toMatchObject({ code: "BLOCKED" });
  });

  it("VIDEO_UNAVAILABLE for private videos", async () => {
    mockYouTube({ playabilityStatus: { status: "ERROR", reason: "Video unavailable" } }, "");
    await expect(innertubeFetcher.fetch("Eux-VGsdw8o")).rejects.toMatchObject({ code: "VIDEO_UNAVAILABLE" });
  });
});

describe("getTranscript", () => {
  it("rejects invalid ids before any network call", async () => {
    await expect(getTranscript("nope")).rejects.toMatchObject({ code: "INVALID_ID" });
  });
});
