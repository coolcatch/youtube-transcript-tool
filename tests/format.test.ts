import { describe, expect, it } from "vitest";
import {
  convert,
  fileName,
  formatClock,
  formatCueTime,
  isFormat,
  toParagraphs,
  toPlainText,
  toSrt,
  toTimestampedText,
  toVtt,
} from "@/lib/format";
import type { Segment, TranscriptResult } from "@/lib/types";

const segs: Segment[] = [
  { start: 0.1, duration: 4.1, text: "So, I'm in my 30s and I have eight" },
  { start: 2.2, duration: 4, text: "different income streams." },
  { start: 4.2, duration: 2, text: "And some are passive." },
];

const result: TranscriptResult = {
  videoId: "Eux-VGsdw8o",
  title: "My 8 Income Sources: $1M+/Year!",
  author: "Someone",
  thumbnailUrl: "x",
  language: "en",
  languageName: "English",
  isAutoGenerated: false,
  tracks: [],
  segments: segs,
  source: "test",
  fetchedAt: "2026-01-01T00:00:00Z",
};

describe("time formatting", () => {
  it("formatClock", () => {
    expect(formatClock(0)).toBe("0:00");
    expect(formatClock(75.9)).toBe("1:15");
    expect(formatClock(3725)).toBe("1:02:05");
    expect(formatClock(-3)).toBe("0:00");
  });
  it("formatCueTime", () => {
    expect(formatCueTime(75.5, ",")).toBe("00:01:15,500");
    expect(formatCueTime(3725.042, ".")).toBe("01:02:05.042");
    expect(formatCueTime(0, ",")).toBe("00:00:00,000");
  });
});

describe("paragraphs", () => {
  it("joins cues into one paragraph when short", () => {
    const p = toParagraphs(segs);
    expect(p).toHaveLength(1);
    expect(p[0].start).toBe(0.1);
    expect(p[0].text).toBe("So, I'm in my 30s and I have eight different income streams. And some are passive.");
  });
  it("splits at sentence ends once long enough", () => {
    const p = toParagraphs(segs, { minChars: 20 });
    expect(p.map((x) => x.text)).toEqual([
      "So, I'm in my 30s and I have eight different income streams.",
      "And some are passive.",
    ]);
    expect(p[1].start).toBe(4.2);
  });
  it("splits on long silences", () => {
    const p = toParagraphs([
      { start: 0, duration: 1, text: "one" },
      { start: 10, duration: 1, text: "two" },
    ]);
    expect(p).toHaveLength(2);
  });
  it("skips empty cues and normalises whitespace", () => {
    const p = toParagraphs([
      { start: 0, duration: 1, text: "  a \n b " },
      { start: 1, duration: 1, text: "   " },
    ]);
    expect(p).toEqual([{ start: 0, text: "a b" }]);
  });
  it("plain and timestamped text", () => {
    expect(toPlainText(segs)).not.toMatch(/\[/);
    expect(toTimestampedText(segs)).toMatch(/^\[0:00\] So,/);
  });
});

describe("subtitle formats", () => {
  it("SRT numbers cues and clamps overlapping ends", () => {
    const srt = toSrt(segs);
    expect(srt).toContain("1\n00:00:00,100 --> 00:00:02,200\nSo, I'm in my 30s and I have eight");
    expect(srt).toContain("3\n00:00:04,200 --> 00:00:06,200\nAnd some are passive.");
    expect(srt.endsWith("\n")).toBe(true);
  });
  it("VTT has header and dot millis", () => {
    const vtt = toVtt(segs);
    expect(vtt.startsWith("WEBVTT\n\n")).toBe(true);
    expect(vtt).toContain("00:00:02.200 --> 00:00:04.200\ndifferent income streams.");
  });
  it("zero-duration cue gets a default length", () => {
    expect(toSrt([{ start: 1, duration: 0, text: "x" }])).toContain("00:00:01,000 --> 00:00:03,000");
  });
});

describe("convert + filenames", () => {
  it("json round-trips", () => {
    expect(JSON.parse(convert(result, "json")).videoId).toBe("Eux-VGsdw8o");
  });
  it("every format produces text", () => {
    for (const f of ["txt", "timestamped", "srt", "vtt", "json"] as const) {
      expect(convert(result, f).length).toBeGreaterThan(10);
    }
  });
  it("isFormat", () => {
    expect(isFormat("srt")).toBe(true);
    expect(isFormat("docx")).toBe(false);
  });
  it("fileName is safe", () => {
    expect(fileName(result, "srt")).toBe("My-8-Income-Sources-1MYear-Eux-VGsdw8o.srt");
    expect(fileName({ ...result, title: "///" }, "txt")).toBe("Eux-VGsdw8o-Eux-VGsdw8o.txt");
    expect(fileName(result, "timestamped")).toMatch(/-timestamps\.txt$/);
  });
});
